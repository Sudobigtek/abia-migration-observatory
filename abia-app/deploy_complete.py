def backup(path):
    if os.path.exists(path):
        bkp = path + ".backup." + str(int(time.time()))
        with open(path, "r") as f:
            old = f.read()
        with open(bkp, "w") as f:
            f.write(old)
        print("[BACKUP] " + os.path.basename(bkp))

def deploy():
    for rel_path, b64_chunks in FILES.items():
        full_path = os.path.join(BASE, rel_path)
        os.makedirs(os.path.dirname(full_path), exist_ok=True)
        backup(full_path)
        b64 = "".join(b64_chunks)
        content = base64.b64decode(b64).decode("utf-8")
        with open(full_path, "w") as f:
            f.write(content)
        print("[WRITE] " + os.path.basename(rel_path) + " (" + str(len(content)) + " chars)")

    print("\n[COMPLETE] All files deployed successfully.")
    print("[NEXT] Run: cd " + BASE + " && source ../.venv/bin/activate && python3 manage.py runserver")

if __name__ == "__main__":
    deploy()
